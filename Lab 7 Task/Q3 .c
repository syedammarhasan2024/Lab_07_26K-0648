# include <stdio.h>
int main(){

    int AmountArr[4][5], SalesSumArr[4] = {0}, ProductSumArr[5] = {0};
    int i, j, Highest, HighestIndex = 1, BonusTotal[4] = {0};

    printf("\n");
    for (i = 0; i < 4; i++){
        for (j = 0; j < 5; j++){
            printf("Enter the sales amount for salesman #%d's product #%d: ", i + 1, j + 1);
            scanf("%d", &AmountArr[i][j]);
        }
        printf("\n");
    }

    for (i = 0; i < 4; i++){
        for (j = 0; j < 5; j++){
            SalesSumArr[i] += AmountArr[i][j];
        }
        printf("The total sales of Salesman #%d are: $%d\n", i+1, SalesSumArr[i]);
    }

    printf("\n");

    for (j = 0; j < 5; j++){
        for (i = 0; i < 4; i++){
            ProductSumArr[j] += AmountArr[i][j];
        }
        printf("The total sales for product #%d are: $%d\n", j + 1, ProductSumArr[j]);
    }

    printf("\n");

    Highest = ProductSumArr[0];

    for (i = 0; i < 5; i++){
        if (ProductSumArr[i] > Highest){
            Highest = ProductSumArr[i];
            HighestIndex = i + 1;
        }
    }

    printf("The highest revenue ($%d) was generated by product #%d\n", Highest, HighestIndex);

    printf("\n");

    for (i = 0; i < 4; i++){
        if (SalesSumArr[i] > 10000){
            BonusTotal[i] = SalesSumArr[i] + (SalesSumArr[i] * 0.10);
            printf("The total sales of salesman #%d are $%d (bonus applied)\n", i + 1, BonusTotal[i]);
            continue;
        }
        printf("The total sales of salesman #%d are $%d (no bonus applied)\n", i + 1, SalesSumArr[i]);
    }

    printf("\n");
    printf("~~~~~~~~~~~~~~~ Final Summary ~~~~~~~~~~~~~~~ \n");
    printf("\n");

    for (i = 0; i < 4; i++){
        printf("Salesman #%d sales: $%d\n", i + 1, SalesSumArr[i]);
    }
    printf("\n");
    for (i = 0; i < 5; i++){
        printf("Product #%d sales: $%d\n", i + 1, ProductSumArr[i]);
    }
    printf("\n");
    for (i = 0; i < 4; i++){
        if (SalesSumArr[i] > BonusTotal[i]){
            printf("Salesman #%d sales (bonus not applied): $%d\n", i + 1, SalesSumArr[i]);
        }
        else {
            printf("Salesman #%d sales (bonus applied)): $%d\n", i + 1, BonusTotal[i]);
        }
    }
    printf("\n");
    printf("The highest revenue of $%d was generated by product #%d", Highest, HighestIndex);
    printf("\n");
}